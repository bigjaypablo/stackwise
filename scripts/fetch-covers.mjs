import { mkdir, writeFile } from "node:fs/promises";

const KEY = process.env.PIXABAY_API_KEY;
if (!KEY) {
  console.error('Set your key first:  export PIXABAY_API_KEY="your-key"');
  process.exit(1);
}

const OUT_DIR = "public/images/covers";
const POOL_FILE = "src/lib/cover-pool.ts";

const QUERIES = {
  crypto: ["bitcoin", "cryptocurrency", "blockchain", "ethereum coin"],
  "ai-tools": ["artificial intelligence", "robot", "machine learning", "technology brain"],
  saas: ["laptop analytics", "office laptop", "coding", "dashboard"],
  reviews: ["gadgets", "smartphone laptop", "magnifying glass", "keyboard typing"],
  comparisons: ["devices technology", "balance scale", "choice decision", "tablet phone laptop"],
  guides: ["notebook pen", "open book", "compass map", "online learning"],
  deals: ["discount sale", "credit card", "piggy bank savings", "gift box"],
};

const used = new Set();
const counts = {};
const credits = [];
const pause = (ms) => new Promise((resolve) => setTimeout(resolve, ms));

async function pick(query) {
  const params = new URLSearchParams({
    key: KEY,
    q: query,
    image_type: "photo",
    orientation: "horizontal",
    safesearch: "true",
    order: "popular",
    min_width: "1200",
    min_height: "700",
    per_page: "12",
  });
  const res = await fetch(`https://pixabay.com/api/?${params}`);
  if (!res.ok) throw new Error(`Pixabay answered ${res.status}`);
  const data = await res.json();
  return (data.hits ?? []).find((hit) => !used.has(hit.id));
}

await mkdir(OUT_DIR, { recursive: true });

for (const [slug, queries] of Object.entries(QUERIES)) {
  let n = 0;
  for (const query of queries) {
    try {
      const hit = await pick(query);
      if (!hit) {
        console.log(`  no new photo for "${query}"`);
        continue;
      }
      const img = await fetch(hit.largeImageURL);
      if (!img.ok) throw new Error(`download answered ${img.status}`);
      const file = `${slug}-${n + 1}.jpg`;
      await writeFile(`${OUT_DIR}/${file}`, Buffer.from(await img.arrayBuffer()));
      n += 1;
      used.add(hit.id);
      credits.push({ file, photographer: hit.user, page: hit.pageURL });
      console.log(`ok  ${file}  (${query})`);
      await pause(600);
    } catch (err) {
      console.log(`FAIL  ${query}: ${err.message}`);
    }
  }
  counts[slug] = n;
}

const pool =
  "// Generated by scripts/fetch-covers.mjs. Photos are from Pixabay (Pixabay Content License).\n" +
  `export const COVER_COUNTS: Record<string, number> = ${JSON.stringify(counts, null, 2)};\n`;
await writeFile(POOL_FILE, pool);
await writeFile(`${OUT_DIR}/credits.json`, JSON.stringify(credits, null, 2) + "\n");
console.log(`\nDone. ${credits.length} photos saved.`);
